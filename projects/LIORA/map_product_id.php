function mapProductId($productStringId) {
    global $GLOBAL_PRODUCT_MAP;
    $productStringId = trim((string) $productStringId);
    if ($productStringId === '') {
        return null;
    }
    
    if (is_numeric($productStringId)) {
        return intval($productStringId);
    }

    return $GLOBAL_PRODUCT_MAP[$productStringId] ?? null;
}

// Reverse map for getting string ID from numeric
$numericToStringId = array_flip($GLOBAL_PRODUCT_MAP);

function getStringId($numericId) {
    global $numericToStringId;
    return $numericToStringId[$numericId] ?? (string)$numericId;
}

// Allow direct JSON lookup when this file is requested as an endpoint.
if (basename($_SERVER['SCRIPT_FILENAME']) === basename(__FILE__) && isset($_GET['id'])) {
    header('Content-Type: application/json; charset=utf-8');
    $requestedId = trim((string)($_GET['id'] ?? ''));
    if ($requestedId === '') {
        echo json_encode(['success' => false, 'message' => 'Empty product id', 'id' => null]);
        exit;
    }

    if (is_numeric($requestedId)) {
        echo json_encode(['success' => true, 'id' => intval($requestedId)]);
        exit;
    }

    $mappedId = mapProductId($requestedId);
    if ($mappedId !== null) {
        echo json_encode(['success' => true, 'id' => $mappedId]);
    } else {
        echo json_encode(['success' => false, 'message' => 'Product mapping not found', 'id' => null]);
    }
    exit;
}

function normalizeStaticProductPrice($price) {
    return floatval(preg_replace('/[^0-9.]/', '', (string) $price));
}

